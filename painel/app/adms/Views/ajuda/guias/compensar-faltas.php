<h2>Para que serve</h2>
<p>Abonar faltas justificadas (atestado médico, licença, convocação de serviço). A falta compensada não conta contra a frequência, e fica registrado quem lançou, quando e por quê.</p>
<h2>Antes de começar</h2>
<p>O professor já lançou as faltas do aluno, e a disciplina está <strong>aberta</strong>. Tenha em mãos o documento: o tipo e o período vão para o registro.</p>
<h2>Passo a passo</h2>
<ol>
<li>Na disciplina, clique em <strong>Faltas</strong> e, na linha do aluno, no botão <strong>Compensar</strong>.</li>
<li>Preencha:</li>
</ol>
<p>- a <strong>quantidade</strong> de faltas compensadas; - o <strong>tipo</strong>: Atestado médico, Licença, Convocação de serviço ou Outro; - o <strong>início</strong> e o <strong>fim</strong> do período; - a <strong>justificativa</strong>, com ao menos 5 caracteres.</p>
<ol>
<li>Clique em <strong>Lançar compensação</strong>. A frequência é recalculada na hora.</li>
<li>O quadro <strong>Histórico de compensações</strong> mostra cada lançamento. Um lançamento errado sai pelo botão de remover, e o total é recalculado.</li>
</ol>
<blockquote>O aluno vê no boletim só a <strong>quantidade</strong> compensada, nunca o motivo. O professor também vê só o número.</blockquote>
<h2>O que pode dar errado</h2>
<ul>
<li><strong>&quot;A justificativa é obrigatória (ao menos 5 caracteres).&quot;</strong> e <strong>&quot;Escolha o tipo da justificativa …&quot;</strong></li>
<li><strong>&quot;O aluno tem N falta(s) e C já compensada(s): dá para compensar no máximo …&quot;</strong> — não se compensa mais do que as faltas.</li>
<li><strong>&quot;O fim do período não pode ser antes do início.&quot;</strong></li>
<li><strong>&quot;A disciplina está ENCERRADA: não aceita compensação nova.&quot;</strong> — só o administrador reabre (<a class="guia-interno" data-guia="reabrir-uma-disciplina" href="{{GUIA}}reabrir-uma-disciplina">Reabrir uma disciplina</a>).</li>
<li>O professor não compensa, a não ser que o administrador ligue para o perfil dele a ação <strong>&quot;Lançar compensação de ausência&quot;</strong> em <a class="guia-interno" data-guia="perfis-de-acesso" href="{{GUIA}}perfis-de-acesso">Perfis de acesso</a>. Ligada, o professor compensa só nas disciplinas em que dá aula; na de outro professor, a tela recusa e diz o porquê.</li>
</ul>
