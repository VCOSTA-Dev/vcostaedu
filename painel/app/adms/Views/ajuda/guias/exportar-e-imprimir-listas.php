<h2>Para que serve</h2>
<p>Encontrar rápido um registro, tirar a lista do sistema (planilha, PDF) ou imprimir. Todas as listas do painel funcionam do mesmo jeito.</p>
<h2>Antes de começar</h2>
<p>Nada: vale para qualquer lista (alunos, disciplinas, notas, faltas, cursos, matérias, emissões…).</p>
<h2>Passo a passo</h2>
<ol>
<li><strong>Pesquisar</strong>: digite no campo <strong>Pesquisar</strong>, à direita. A lista filtra enquanto você digita.</li>
<li><strong>Ordenar</strong>: clique no título da coluna; clique de novo para inverter.</li>
<li><strong>Mostrar</strong>: no pé da lista, escolha 10, 25, 50, 100 ou Todos por página.</li>
<li><strong>Exportar</strong>: botões no topo da lista.</li>
</ol>
<p>- <strong>Excel</strong>: planilha; - <strong>CSV</strong>: texto separado por ponto e vírgula, que abre direto no Excel em português; - <strong>PDF</strong>: em paisagem, quando a lista tem muitas colunas; - <strong>Imprimir</strong>: só a lista.</p>
<p>A exportação leva o que está filtrado na tela e deixa de fora a coluna Ações.</p>
<ol>
<li><strong>Ações</strong>: os botões pequenos de cada linha (ver, editar, apagar…). Passe o mouse para ver a dica. Um botão <strong>apagado</strong> (desabilitado) diz na dica <strong>por que</strong> não pode ser usado.</li>
</ol>
<h2>O que pode dar errado</h2>
<ul>
<li>A lista exportada veio curta: há um texto no campo <strong>Pesquisar</strong>. Limpe o campo e exporte de novo.</li>
<li>O botão de uma ação está apagado: leia a dica (ex.: &quot;Em uso: 1 grade(s)… Não pode ser apagado.&quot;, &quot;Disciplina encerrada: reabra antes de editar&quot;).</li>
</ul>
