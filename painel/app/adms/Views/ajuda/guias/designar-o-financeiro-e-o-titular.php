<h2>Para que serve</h2>
<p>O papel vale para um aluno e para um ano letivo:</p>
<ul>
<li><strong>Responsável financeiro:</strong> exatamente um. A cobrança é emitida em nome de uma pessoa só; o sistema nunca aceita dois ao mesmo tempo.</li>
<li><strong>Responsável acadêmico titular:</strong> um, o do contrato. Pode ser a mesma pessoa do financeiro ou outra.</li>
</ul>
<p>Os papéis de um ano não valem para outro: em cada ano letivo, a escola designa de novo (ou copia do ano anterior).</p>
<h2>Antes de começar</h2>
<ul>
<li>O ano letivo aberto em <strong>Ensino → Ano letivo e etapas</strong>.</li>
<li>A pessoa cadastrada, ou os dados dela à mão (dá para cadastrar no mesmo formulário).</li>
</ul>
<h2>Passo a passo</h2>
<ol>
<li>Abra a ficha do aluno, a aba <strong>Responsáveis</strong>, e clique em <strong>Abrir os responsáveis do aluno</strong>.</li>
<li>Escolha o <strong>ano letivo</strong> no alto da tela.</li>
<li>No quadro <strong>Responsável financeiro</strong>, clique em <strong>Designar</strong>. Escolha uma pessoa já ligada ao aluno, ou <strong>Outra pessoa (cadastrar agora)</strong> e preencha o nome, o e-mail, o celular, o CPF e o parentesco. Clique em <strong>Designar</strong>.</li>
<li>Faça o mesmo no quadro <strong>Responsável acadêmico titular</strong>. Se o titular for o financeiro, ele já vem escolhido na lista.</li>
<li>O histórico, no fim da tela, guarda quem designou, quando e o que havia antes.</li>
</ol>
<h2>O que pode dar errado</h2>
<ul>
<li><strong>&quot;Já há um responsável deste papel em vigor neste ano&quot;:</strong> o papel já tem alguém. Para pôr outra pessoa, use <strong>Trocar</strong> (veja o guia &quot;Trocar o responsável financeiro&quot;).</li>
<li><strong>&quot;Escolha o ano letivo&quot;:</strong> abra o ano letivo da escola antes.</li>
</ul>
