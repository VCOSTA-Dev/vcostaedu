<h2>Para que serve</h2>
<p>Conferir tudo o que entra no histórico, sem o formato de documento, e resolver o que falta antes de emitir.</p>
<h2>Antes de começar</h2>
<p>O aluno tem matrícula no curso.</p>
<h2>Passo a passo</h2>
<ol>
<li>Menu <strong>Educacional → Prévia do histórico</strong> (ou o botão na aba Matrículas). Busque por RA ou nome e escolha a matrícula.</li>
<li>Confira:</li>
</ol>
<p>- o aluno; - a matrícula: polo, modalidade, ingresso e conclusão; - a instituição e o <strong>ato legal</strong>; - as disciplinas da grade com <strong>todas as tentativas</strong> (a vigente em destaque): docente, titulação, datas de realização, média, frequência e resultado; - o TCC e os totais.</p>
<ol>
<li>Resolva os <strong>alertas</strong> do topo. O histórico FINAL só sai sem nenhum alerta.</li>
<li>Na barra do topo:</li>
</ol>
<p>- <strong>Prévia em PDF — parcial</strong> ou <strong>— final</strong>: o documento com a tarja PRÉVIA; nada é gravado; - <strong>Imprimir esta conferência</strong>; - <strong>Ir para a ficha do aluno</strong>: para corrigir dados pessoais ou a matrícula; - <strong>Emitir histórico</strong>.</p>
