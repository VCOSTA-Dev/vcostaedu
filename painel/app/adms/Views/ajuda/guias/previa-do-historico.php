<h2>O que pode dar errado</h2>
<ul>
<li><strong>&quot;Dados pessoais do aluno incompletos (ficha do aluno → Editar): falta …&quot;</strong> — complete a ficha (nascimento, naturalidade, nacionalidade, RG, CPF, filiação).</li>
<li><strong>&quot;Ato legal não definido: …&quot;</strong> — nenhum ato ativo e vigente para a modalidade da matrícula (ou mais de um): <a class="guia-interno" data-guia="dados-da-instituicao-e-atos-legais" href="{{GUIA}}dados-da-instituicao-e-atos-legais">Dados da instituição e atos legais</a>.</li>
<li><strong>&quot;… disciplina sem docente.&quot;</strong> e <strong>&quot;… oferta sem período de realização.&quot;</strong> — <a class="guia-interno" data-guia="completar-a-oferta" href="{{GUIA}}completar-a-oferta">Completar a oferta</a>.</li>
<li><strong>&quot;…: docente … sem titulação.&quot;</strong> — o administrador informa a titulação no cadastro do professor.</li>
<li><strong>&quot;O curso exige TCC e …&quot;</strong> — <a class="guia-interno" data-guia="concluir-o-curso-e-tcc" href="{{GUIA}}concluir-o-curso-e-tcc">Concluir o curso e registrar o TCC</a>.</li>
<li><strong>Prévia em PDF</strong> desabilitado: não há modelo ativo daquele tipo para o curso (Modelos de histórico).</li>
</ul>
