<h2>Para que serve</h2>
<p>Para a escola saber o que a família encontra no portal e responder às dúvidas dela. O que cada pessoa vê depende do papel dela em cada aluno, em cada ano (Responsáveis, na ficha do aluno).</p>
<h2>Antes de começar</h2>
<ul>
<li>O responsável está designado no aluno, no ano (titular, financeiro ou acesso adicional).</li>
<li>Ele já criou a senha pelo convite e entra no portal.</li>
</ul>
<h2>Passo a passo</h2>
<ol>
<li>O responsável entra no portal com o login dele (o CPF ou o e-mail escolhido no convite) e a senha.</li>
<li>Com mais de um filho, ele vê a lista <strong>Meus filhos</strong> e escolhe um. Com um filho só, entra direto nele.</li>
<li>No alto de toda tela aparecem o nome do filho, a turma e o ano. Ali ele troca de filho e de ano. Só aparecem os anos em que ele tem papel naquele aluno.</li>
<li>Pelas abas, ele abre:</li>
</ol>
<p>- <strong>Boletim</strong>: o mesmo boletim que o aluno vê, com a mesma regra de liberação das notas; - <strong>Notas</strong>: as notas das atividades de cada disciplina; - <strong>Frequência</strong>: as faltas e a frequência de cada disciplina; - <strong>Horário</strong>: o horário da turma; - <strong>Atestado</strong>: emite o atestado de matrícula da matrícula em curso e abre o PDF dos que já foram emitidos.</p>
<p>Tudo é só para leitura. O responsável não vê a senha do aluno, os outros responsáveis nem o ambiente de estudo.</p>
<h2>O que pode dar errado</h2>
<ul>
<li><strong>&quot;Acesso não permitido&quot;:</strong> a pessoa abriu um aluno ou um ano em que não tem papel (por exemplo, um endereço copiado de outra família). Confira as designações na ficha do aluno.</li>
<li><strong>&quot;Ainda não há nenhum aluno liberado para você&quot;:</strong> o responsável não tem papel em vigor em nenhum aluno, ou tem só o acesso adicional e a escola desligou o acesso adicional nas Regras da escola.</li>
<li><strong>O ano não aparece no seletor:</strong> não há designação dele naquele aluno, naquele ano.</li>
</ul>
