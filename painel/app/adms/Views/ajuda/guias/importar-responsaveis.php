<h2>Para que serve</h2>
<p>Para designar os responsáveis de muitos alunos de uma vez, como no começo do ano.</p>
<h2>Antes de começar</h2>
<ul>
<li>Os alunos cadastrados (o RA) e o ano letivo aberto.</li>
<li>A planilha em CSV, com as colunas: <strong>ra; ano; papel; nome; email; celular; cpf; parentesco; motivo</strong>. Baixe o modelo na tela.</li>
</ul>
<h2>Passo a passo</h2>
<ol>
<li>No menu, abra <strong>Responsáveis</strong> (junto de Alunos) e clique em <strong>Importar planilha</strong>.</li>
<li>Clique em <strong>Baixar o modelo</strong>, preencha uma linha por papel: o RA do aluno, o ano, o papel (<strong>financeiro</strong> ou <strong>titular</strong>) e os dados da pessoa. A coluna <strong>motivo</strong> só se preenche para trocar quem já está no papel.</li>
<li>Escolha o arquivo e clique em <strong>Conferir</strong>. A tela mostra cada linha e o que vai acontecer: designa, troca, ou &quot;já está assim&quot;.</li>
<li>Com tudo certo, clique em <strong>Aplicar a planilha</strong>.</li>
</ol>
<h2>O que pode dar errado</h2>
<ul>
<li><strong>Linhas em vermelho:</strong> a linha tem problema (o aluno não existe, o ano não está aberto, o papel está errado, o e-mail ou o CPF não é válido, duas linhas dão o mesmo papel ao mesmo aluno). Nada é gravado: corrija a planilha e envie de novo.</li>
<li><strong>&quot;O acesso acadêmico adicional não entra pela planilha&quot;:</strong> ele pede o motivo; libere pela tela do aluno.</li>
<li><strong>&quot;O aluno já tem … neste papel; para trocar, preencha o motivo&quot;:</strong> preencha a coluna motivo, se a troca for mesmo para acontecer.</li>
</ul>
