<h2>Para que serve</h2>
<p>Às vezes o convite foi para o lugar errado, ou a escola precisa suspender o acesso de alguém ao portal. Os papéis da pessoa nos alunos continuam registrados; só o acesso muda.</p>
<h2>Antes de começar</h2>
<ul>
<li>O responsável está cadastrado (Responsáveis).</li>
</ul>
<h2>Passo a passo</h2>
<p><strong>Cancelar o convite:</strong></p>
<ol>
<li>Abra o responsável (<strong>Responsáveis</strong>, clique no nome).</li>
<li>No quadro <strong>Acesso ao portal</strong>, clique em <strong>Cancelar o convite</strong>. O link deixa de valer na hora.</li>
</ol>
<p><strong>Bloquear o acesso:</strong></p>
<ol>
<li>No mesmo quadro, abra <strong>Bloquear o acesso</strong>.</li>
<li>Escreva o <strong>motivo</strong> e clique em <strong>Bloquear</strong>.</li>
<li>A pessoa não entra mais no portal. Se ela estava com o portal aberto, sai na próxima página. O convite em aberto, se havia, é cancelado.</li>
</ol>
<p>Para devolver o acesso, clique em <strong>Desbloquear o acesso</strong>. A senha da pessoa continua a mesma.</p>
<h2>O que pode dar errado</h2>
<ul>
<li><strong>&quot;Informe o motivo do bloqueio&quot;:</strong> o motivo é obrigatório; ele fica no histórico do responsável.</li>
<li><strong>&quot;O acesso desta pessoa está bloqueado. Desbloqueie antes de convidar&quot;:</strong> o convite não é gerado para quem está bloqueado.</li>
</ul>
