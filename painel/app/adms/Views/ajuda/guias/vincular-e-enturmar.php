<h2>Para que serve</h2>
<p>Ligar o aluno ao curso (a matrícula) e às disciplinas do ano (a enturmação). Sem enturmação, o aluno não aparece para o professor.</p>
<h2>Antes de começar</h2>
<p>A oferta do ano foi gerada e o aluno está cadastrado.</p>
<h2>Passo a passo</h2>
<ol>
<li>Na ficha do aluno, aba <strong>Matrículas → Vincular a um curso</strong>. Preencha:</li>
</ol>
<p>- o ano; - o <em>curso — grade</em>; - a forma e a data de ingresso; - o <strong>polo</strong> e a <strong>modalidade da matrícula</strong> (vazio = os do curso); - a <strong>previsão de conclusão</strong> (opcional). Depois do vínculo, a edição da matrícula mostra <strong>Usar a sugestão</strong>: a maior data de fim das ofertas da grade. Ela e o ingresso saem nos documentos como &quot;março de 2027&quot;.</p>
<p>A modalidade da matrícula escolhe o ato legal do histórico.</p>
<figure><img src="{{IMG}}secretaria_12_vinculo.png" alt="Aba Matrículas com polo e modalidade da matrícula"><figcaption>Aba Matrículas com polo e modalidade da matrícula</figcaption></figure>
<ol>
<li>Clique no botão <strong>Enturmação</strong> do ano. Vêm <strong>sugeridas e marcadas</strong> as ofertas abertas das disciplinas da grade que o aluno ainda não cursou com aprovação. Desmarque o que ele cursará depois, acrescente outra se precisar, e clique em <strong>Confirmar enturmação</strong>.</li>
</ol>
<figure><img src="{{IMG}}secretaria_13_enturmacao.png" alt="Enturmação de uma aluna com ajuste"><figcaption>Enturmação de uma aluna com ajuste</figcaption></figure>
<ol>
<li>Num ano seguinte, clique em <strong>Registrar no ano</strong>, na aba Matrículas, e abra a Enturmação desse ano. Nada grava antes de confirmar.</li>
</ol>
<h2>O que pode dar errado</h2>
<ul>
<li><strong>&quot;A grade N de … está Desativada e não aceita vínculo novo.&quot;</strong></li>
<li><strong>&quot;Informe a data de ingresso.&quot;</strong></li>
<li><strong>&quot;«Disciplina»: oferta encerrada — o administrador precisa reabrir. Nada foi gravado.&quot;</strong> — a disciplina já foi encerrada; na tela, ela aparece bloqueada.</li>
<li>A disciplina com nota, falta ou observação não sai da enturmação.</li>
<li>Uma disciplina &quot;já aprovada&quot; não vem sugerida: o aluno já passou nela em outra oferta.</li>
</ul>
