<h2>Para que serve</h2>
<p>Ver <strong>como está a instituição agora</strong>, num relance, e descer até a lista de qualquer número.</p>
<h2>Antes de começar</h2>
<ul>
<li>Taxa de aprovação, reprovação e frequência média usam só os resultados <strong>gravados</strong> de ofertas <strong>encerradas</strong>. O período filtra a data do encerramento.</li>
<li>Pendentes, ofertas com pendência e atrasadas olham as ofertas <strong>abertas</strong>.</li>
<li>Na escola, o resultado de uma oferta encerrada é o <strong>resultado anual</strong>: as etapas fechadas, a média anual, a frequência e a decisão do conselho de classe.</li>
<li>Numa instalação pequena, o painel abre de uma vez. Numa grande, as notas são calculadas em partes, numa janela de progresso, e o painel abre no fim.</li>
</ul>
<h2>Passo a passo</h2>
<ol>
<li>Abra <strong>Relatórios → Painel acadêmico</strong>. Filtre por curso e, se quiser, pelo período de encerramento.</li>
<li>Leia os cartões:</li>
</ol>
<p>- <strong>Alunos ativos</strong>: alunos com matrícula em Cursando; - <strong>Matrículas</strong> por situação (Cursando, Concluído, Trancado, Cancelado, Transferido); - <strong>Ofertas</strong> abertas e encerradas; - <strong>Taxa de aprovação</strong>, <strong>Reprovação por nota</strong> e <strong>por frequência</strong>: quem reprovou pelos dois motivos conta nos dois percentuais; - <strong>Frequência média</strong> dos resultados gravados; - <strong>Alunos em risco</strong>, <strong>Pendentes</strong>, <strong>Ofertas com pendência</strong> e <strong>Ofertas atrasadas</strong> (a data de fim já passou).</p>
<ol>
<li>Clique no número, ou em &quot;Ver a lista (n)&quot; nos percentuais, para ver quem compõe o número.</li>
</ol>
<h2>O que pode dar errado</h2>
<ul>
<li>Os percentuais aparecem como &quot;—&quot;: não há oferta encerrada no período escolhido.</li>
<li>Uma oferta aparece como atrasada, mas a turma já terminou: falta encerrar a disciplina (ou corrigir a data de fim).</li>
</ul>
