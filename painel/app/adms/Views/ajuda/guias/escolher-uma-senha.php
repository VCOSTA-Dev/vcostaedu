<h2>Para que serve</h2>
<p>Definir uma senha que proteja a sua conta, em qualquer tela de senha do sistema: o primeiro acesso, o &quot;Esqueci a senha&quot;, a troca da sua senha no Perfil e o cadastro de um usuário.</p>
<h2>Antes de começar</h2>
<p>A regra é a mesma em todas as telas, no painel e no portal:</p>
<ul>
<li>pelo menos <strong>12 caracteres</strong>;</li>
<li><strong>não</strong> é preciso usar símbolo, número ou letra maiúscula: o que protege é o comprimento;</li>
<li>espaços são aceitos, então uma frase serve como senha.</li>
</ul>
<h2>Passo a passo</h2>
<ol>
<li>Clique no campo da senha e digite. Abaixo do campo, a barra mostra a força: <strong>Aceitável</strong>, <strong>Boa</strong> ou <strong>Forte</strong>. Quanto mais longa a senha, mais forte.</li>
<li>Para conferir o que digitou, clique em <strong>Mostrar</strong>; clique em <strong>Ocultar</strong> para esconder de novo.</li>
<li>Se a tela pedir a senha duas vezes, digite a mesma nas duas. Um aviso aparece enquanto elas forem diferentes.</li>
<li>Clique no botão de salvar da tela. Colar a senha e usar o gerenciador de senhas do navegador funcionam normalmente.</li>
</ol>
<h2>O que pode dar errado</h2>
<ul>
<li><strong>&quot;A senha precisa ter pelo menos 12 caracteres.&quot;</strong> — acrescente palavras até chegar a 12 ou mais.</li>
<li><strong>&quot;Esta senha é muito comum e fácil de adivinhar. Escolha outra.&quot;</strong> — a senha está numa lista de senhas muito usadas (também com números no fim, como &quot;palavra2026&quot;). Escolha uma frase só sua.</li>
<li><strong>&quot;A senha não pode conter o seu nome, o seu usuário ou o seu e-mail.&quot;</strong> — tire da senha essas partes.</li>
<li>A barra fica vermelha e diz <strong>&quot;Curta demais&quot;</strong> ou <strong>&quot;Muito comum&quot;</strong>: é só um aviso antes de enviar; a conferência que vale é a do sistema, ao salvar.</li>
</ul>
