<h2>Para que serve</h2>
<p>A pessoa responsável (a mãe, o pai, a avó, um tutor) tem um cadastro só, mesmo que seja responsável por mais de um aluno. No cadastro: o nome, o e-mail, o celular e o CPF (opcional). O parentesco fica em cada aluno: a mesma pessoa pode ser a mãe de um e a tia de outro.</p>
<p>Para entrar no portal, a pessoa precisa de <strong>e-mail ou de CPF</strong>: é com um deles que ela entra.</p>
<h2>Antes de começar</h2>
<ul>
<li>A instalação é do tipo escola.</li>
<li>O aluno já está cadastrado.</li>
</ul>
<h2>Passo a passo</h2>
<ol>
<li>No menu, abra <strong>Responsáveis</strong> (junto de Alunos) e clique em <strong>Novo responsável</strong>. Ou, na ficha do aluno, abra a aba <strong>Responsáveis</strong> e clique em <strong>Abrir os responsáveis do aluno</strong>: ali a pessoa já nasce ligada ao aluno, com o parentesco.</li>
<li>Preencha o nome, o e-mail, o celular e, se tiver, o CPF.</li>
<li>Ao digitar o e-mail ou o CPF, o sistema procura se a pessoa já existe. Se já existe, ele avisa e mostra o cadastro: use-o em vez de criar outro.</li>
<li>Clique em <strong>Salvar</strong>.</li>
<li>Em <strong>Responsáveis</strong>, a lista mostra cada pessoa com os alunos, o papel em cada ano e a situação do acesso ao portal. A busca acha pelo nome, pelo e-mail, pelo CPF, pelo celular, ou pelo nome ou o RA do aluno.</li>
</ol>
<h2>O que pode dar errado</h2>
<ul>
<li><strong>&quot;Já existe uma pessoa com este e-mail ou este CPF&quot;:</strong> a pessoa já está cadastrada. Abra o cadastro dela e designe o papel no aluno.</li>
<li><strong>&quot;O CPF não é válido&quot;:</strong> confira os números. O CPF é opcional: pode deixar em branco.</li>
<li><strong>&quot;Sem e-mail e sem CPF, a pessoa não consegue entrar no portal&quot;:</strong> o cadastro vale, mas para o acesso ao portal ela precisa de um dos dois.</li>
</ul>
