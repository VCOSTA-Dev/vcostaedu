<h2>Para que serve</h2>
<p>Responder às perguntas do dia a dia da secretaria: quem está matriculado e em que situação, quem está nesta turma, quantos devem concluir em cada mês e que dados faltam para emitir documentos.</p>
<h2>Antes de começar</h2>
<ul>
<li>Uma linha por <strong>matrícula</strong>: o aluno com dois cursos aparece duas vezes.</li>
<li>O professor vê só a <strong>Lista de turma</strong> das ofertas dele.</li>
</ul>
<h2>Passo a passo</h2>
<ol>
<li><strong>Alunos por curso e situação</strong>: filtre por curso, grade, situação, polo, coorte (semestre de ingresso) ou período de ingresso. O nome abre o desempenho do aluno.</li>
<li><strong>Lista de turma</strong>: escolha a oferta. Use <strong>PDF</strong> ou <strong>Imprimir</strong> para o diário de papel (a coluna Assinatura vai em branco).</li>
<li><strong>Previsão de conclusão</strong>: matrículas em Cursando por mês da previsão. A linha &quot;sem previsão&quot; mostra quem ainda não tem a data.</li>
<li><strong>Qualidade do cadastro</strong>: o que falta em cada matrícula (sexo, CPF, nascimento, naturalidade, nacionalidade, RG, filiação, previsão, enturmação) e a contagem por tipo. &quot;Editar&quot; abre a ficha do aluno.</li>
</ol>
<h2>O que pode dar errado</h2>
<ul>
<li>O histórico avisa &quot;dados pessoais incompletos&quot;: abra Qualidade do cadastro, filtre pelo curso e complete as fichas listadas.</li>
<li>Um aluno não aparece na Lista de turma: ele não está enturmado na oferta (ou a enturmação está inativa).</li>
</ul>
