<h2>Para que serve</h2>
<p>Durante o ano, o responsável financeiro ou o titular pode mudar. A troca guarda as duas coisas: até quando o anterior foi responsável e desde quando o novo é. O histórico de quem foi fica.</p>
<h2>Antes de começar</h2>
<ul>
<li>O aluno já tem alguém no papel, no ano letivo escolhido.</li>
</ul>
<h2>Passo a passo</h2>
<ol>
<li>Abra os responsáveis do aluno (a ficha do aluno, aba <strong>Responsáveis</strong>) e escolha o ano letivo.</li>
<li>No quadro do papel, clique em <strong>Trocar</strong>.</li>
<li>Escolha a nova pessoa (ou cadastre agora), a data <strong>a partir de</strong> quando ela assume e o <strong>motivo da troca</strong>, que é obrigatório.</li>
<li>Clique em <strong>Trocar</strong>. A pessoa anterior fica em <strong>Papéis encerrados</strong>, com a data e o motivo.</li>
</ol>
<p>Para tirar o papel sem pôr outra pessoa, use <strong>Encerrar sem pôr outra pessoa</strong>, também com a data e o motivo.</p>
<h2>O que pode dar errado</h2>
<ul>
<li><strong>&quot;A troca pede o motivo&quot;:</strong> preencha o motivo.</li>
<li><strong>&quot;A data da troca não pode ser antes do início do responsável atual&quot;:</strong> escolha uma data a partir do início dele.</li>
</ul>
