<h2>Para que serve</h2>
<p>No ano novo, quase sempre os responsáveis são os mesmos. Em vez de designar tudo de novo, copie do ano anterior e confira.</p>
<h2>Antes de começar</h2>
<ul>
<li>Os dois anos letivos abertos em <strong>Ensino → Ano letivo e etapas</strong>.</li>
</ul>
<h2>Passo a passo</h2>
<ol>
<li>Abra os responsáveis do aluno e escolha o <strong>ano novo</strong>.</li>
<li>Clique em <strong>Copiar do ano anterior</strong>. A tela mostra o que será copiado: o financeiro e o titular do ano anterior. Nada é gravado ainda.</li>
<li>Se o ano novo já tem alguém num papel, esse papel fica como está.</li>
<li>Clique em <strong>Confirmar e gravar</strong>.</li>
</ol>
<p>Os acessos acadêmicos adicionais não são copiados: valem só para o ano em que foram liberados. Libere de novo, se for o caso.</p>
<h2>O que pode dar errado</h2>
<ul>
<li><strong>&quot;Nada a copiar&quot;:</strong> os papéis do ano novo já estão preenchidos, ou o ano anterior não tinha ninguém designado.</li>
<li><strong>O botão não aparece:</strong> o ano anterior não está aberto em Ano letivo e etapas.</li>
</ul>
