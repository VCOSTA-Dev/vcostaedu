<h2>Para que serve</h2>
<p>O responsável entra no portal com o login que ele escolhe no convite (o e-mail ou o CPF do cadastro) e uma senha que ele mesmo cria. O convite é o caminho para essa primeira senha: um link que vale uma vez só e por poucos dias (7, se a escola não mudou em <strong>Regras da escola</strong>).</p>
<h2>Antes de começar</h2>
<ul>
<li>A pessoa está cadastrada com <strong>e-mail ou CPF</strong>: um deles será o login dela no portal.</li>
<li>A pessoa tem um papel em algum aluno (financeiro, titular ou acesso adicional).</li>
</ul>
<h2>Passo a passo</h2>
<ol>
<li>Abra o responsável: <strong>Responsáveis</strong>, clique no nome dele. (Na lista, o botão <strong>Gerar convite</strong> também gera e abre a ficha.)</li>
<li>No quadro <strong>Acesso ao portal</strong>, clique em <strong>Gerar convite</strong>.</li>
<li>O link aparece logo abaixo, só agora e só para você. Escolha como entregar:</li>
</ol>
<p>- <strong>Enviar por e-mail</strong>, quando a pessoa tem e-mail e o envio está configurado em <strong>Configurações → E-mail (SMTP)</strong>; - <strong>Copiar o link</strong> ou <strong>Copiar a mensagem</strong>, para mandar por onde preferir; - <strong>Abrir no WhatsApp</strong>, que abre o seu WhatsApp com a mensagem pronta para o celular do cadastro.</p>
<ol>
<li>A pessoa abre o link, confere o nome, vê o primeiro nome dos alunos dela, cria a senha e entra.</li>
</ol>
<p>O texto da mensagem fica em <strong>Regras da escola</strong>, no quadro <strong>Responsáveis</strong>.</p>
<h2>O que pode dar errado</h2>
<ul>
<li><strong>&quot;Para o convite, a pessoa precisa de e-mail ou de CPF&quot;:</strong> edite o cadastro e preencha um dos dois.</li>
<li><strong>&quot;Esta pessoa ainda não tem papel em nenhum aluno&quot;:</strong> designe o papel na ficha do aluno, aba <strong>Responsáveis</strong>, antes de convidar.</li>
<li><strong>A pessoa diz que o link &quot;não vale mais&quot;:</strong> ele já foi usado, venceu ou foi trocado por um convite mais novo. Gere outro.</li>
<li><strong>Você saiu da ficha antes de entregar o link:</strong> o link não fica guardado. Gere outro; o anterior deixa de valer.</li>
<li><strong>O botão &quot;Enviar por e-mail&quot; não aparece:</strong> a pessoa não tem e-mail, ou o envio de e-mail não está configurado. Use o link ou o WhatsApp.</li>
</ul>
