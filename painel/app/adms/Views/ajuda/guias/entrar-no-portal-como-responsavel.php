<h2>Para que serve</h2>
<p>Para orientar a família: como entrar a primeira vez, como entrar depois e o que fazer quando a senha foi esquecida.</p>
<h2>Antes de começar</h2>
<ul>
<li>A pessoa recebeu o convite da escola (ou já criou a senha por ele).</li>
</ul>
<h2>Passo a passo</h2>
<p><strong>A primeira vez:</strong></p>
<ol>
<li>A pessoa abre o link do convite que recebeu da escola.</li>
<li>Confere o nome dela e o primeiro nome dos alunos.</li>
<li>Escolhe com o que vai entrar no portal: o <strong>e-mail</strong> ou o <strong>CPF</strong> do cadastro (quando o cadastro tem os dois). É o <strong>login</strong> da pessoa: só ele entra. Quando o cadastro tem um só, ele é o login.</li>
<li>Cria a senha (pelo menos 12 caracteres; uma frase longa é o melhor) e clica em <strong>Criar a senha e entrar</strong>.</li>
</ol>
<p><strong>As próximas vezes:</strong></p>
<ol>
<li>Na entrada do portal, no campo <strong>Login</strong>, a pessoa digita o login dela: o <strong>CPF</strong> (com ou sem os pontos e o traço) ou o <strong>e-mail</strong>, o que escolheu no convite.</li>
<li>Digita a senha e clica em <strong>Acessar</strong>.</li>
</ol>
<p><strong>Esqueceu a senha:</strong></p>
<ul>
<li>Com e-mail cadastrado: em <strong>Esqueci a senha</strong>, informa o login (o CPF ou o e-mail); o link vai para o e-mail do cadastro. Chega um link que vale por 2 horas, uma vez só, para criar uma senha nova. (É preciso o envio de e-mail configurado em <strong>Configurações → E-mail (SMTP)</strong>.)</li>
<li>Sem e-mail cadastrado: a escola gera um convite novo pela ficha do responsável; ele cria uma senha nova por esse link.</li>
</ul>
<h2>O que pode dar errado</h2>
<ul>
<li><strong>&quot;Usuário ou senha incorretos&quot;:</strong> confira o login (o que a pessoa escolheu no convite; a ficha do responsável mostra qual é) e a senha. O e-mail ou o CPF que não é o login não entra. Depois de várias tentativas erradas, o portal pede para esperar alguns minutos.</li>
<li><strong>&quot;O seu acesso ao portal está bloqueado&quot;:</strong> a escola bloqueou o acesso; veja o motivo na ficha do responsável.</li>
<li><strong>&quot;Este link não vale mais&quot;:</strong> o link foi usado, venceu ou foi trocado por um mais novo. Peça outro.</li>
<li><strong>A pessoa quer entrar com o outro identificador:</strong> na ficha do responsável, em <strong>Acesso ao portal</strong>, <strong>Trocar o login</strong> (o e-mail ou o CPF do cadastro). A senha continua a mesma.</li>
<li><strong>&quot;… já é o login de outro responsável&quot;:</strong> dois logins iguais não existem. Use o outro identificador da pessoa, ou troque antes o login da outra conta.</li>
</ul>
