<h2>O que pode dar errado</h2>
<ul>
<li><strong>&quot;Conclusão RECUSADA — falta: …&quot;</strong> — a lista diz o que falta: disciplina &quot;Em curso&quot;, &quot;Reprovado&quot; ou &quot;Não cursada&quot;, ou o TCC. Nada é salvo.</li>
<li><strong>&quot;A data de conclusão não pode ser antes do ingresso.&quot;</strong></li>
<li>TCC: <strong>&quot;Informe o título do TCC (até 500 caracteres).&quot;</strong>, <strong>&quot;O orientador deve ser um professor ativo.&quot;</strong>, <strong>&quot;Nota inválida: use um número de 0 a 10 com até 2 casas decimais (vírgula ou ponto).&quot;</strong> e, com nota abaixo da mínima, <strong>&quot;Nota abaixo da média mínima (7,0): o TCC não pode ficar &quot;Aprovado&quot;.&quot;</strong></li>
</ul>
