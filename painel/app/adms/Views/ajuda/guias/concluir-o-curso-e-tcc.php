<h2>Para que serve</h2>
<p>Registrar o trabalho de conclusão e marcar a matrícula como <strong>Concluída</strong> — o que libera o histórico FINAL.</p>
<h2>Antes de começar</h2>
<p>Todas as disciplinas da grade estão <strong>aprovadas</strong> em disciplinas <strong>encerradas</strong>. Se o curso exige TCC, ele está aprovado.</p>
<h2>Passo a passo</h2>
<ol>
<li>Ficha do aluno, aba <strong>Matrículas</strong>, bloco <strong>TCC</strong>: título, orientador (um professor), nota, data da defesa ou entrega e situação. Salve.</li>
<li>Em <strong>Salvar matrícula</strong>, escolha <strong>Concluído</strong> e informe a <strong>data de conclusão</strong>.</li>
</ol>
