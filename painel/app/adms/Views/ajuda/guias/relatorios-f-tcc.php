<h2>Para que serve</h2>
<p>Ver <strong>como estão os TCC de quem vai concluir</strong> e cobrar quem ainda não tem TCC.</p>
<h2>Antes de começar</h2>
<p>Entram as matrículas de cursos que <strong>exigem TCC</strong> e as que têm TCC lançado. A nota mínima é a da <strong>regra do TCC e dos documentos</strong> do curso.</p>
<h2>Passo a passo</h2>
<ol>
<li>Abra <strong>Relatórios → Situação do TCC</strong>. Filtre por curso, situação da matrícula, previsão de conclusão ou situação do TCC.</li>
<li>Os cartões contam <strong>Sem TCC</strong>, <strong>Em andamento</strong>, <strong>Aprovado</strong> e <strong>Reprovado</strong>. Clique para ver a lista.</li>
<li>A tabela traz a nota, a nota mínima, o orientador e a data da defesa.</li>
</ol>
<h2>O que pode dar errado</h2>
<ul>
<li>O aluno aparece &quot;Sem TCC&quot; mas já defendeu: lance o TCC na ficha do aluno (aba Matrícula).</li>
<li>A nota mínima não é a esperada: confira a &quot;Regra de média do TCC e dos documentos&quot; no curso.</li>
</ul>
