<h2>Para que serve</h2>
<p>Ver a tarefa acontecendo antes de fazer: cada guia tem um vídeo curto que mostra o passo a passo do começo ao fim, na demonstração (com dados inventados).</p>
<h2>Antes de começar</h2>
<p>Você precisa estar logado. Cada perfil vê os vídeos dos guias dele.</p>
<h2>Passo a passo</h2>
<ol>
<li>Abra um guia (<strong>Ajuda → Central de ajuda</strong>). O vídeo fica no topo, antes do texto. Ele só carrega quando você clica para tocar.</li>
<li>A <strong>legenda</strong> já vem ligada: é a narração de cada passo. Para desligar ou mudar a velocidade, use os controles do próprio vídeo.</li>
<li>Ao lado do vídeo, os <strong>capítulos</strong>: clique em um para pular direto para aquele trecho. O capítulo que está tocando fica marcado.</li>
<li>Abaixo do vídeo, <strong>Ler a transcrição</strong> abre todo o texto narrado.</li>
<li>Em <strong>Ajuda → Vídeos</strong> (ou no botão <strong>Vídeos</strong> da Central de ajuda) ficam todos os vídeos do seu perfil, com a duração. Digite no campo de busca uma palavra do título ou do que é dito no vídeo.</li>
</ol>
<h2>O que pode dar errado</h2>
<ul>
<li><strong>O guia não mostra vídeo</strong> — o vídeo daquele guia ainda não foi copiado para o servidor. O texto do guia continua valendo; avise o administrador.</li>
<li><strong>&quot;Ainda não há vídeos para os guias do seu perfil.&quot;</strong> — a página Vídeos está vazia porque a pasta de vídeos não está no servidor.</li>
<li><strong>O vídeo não avança para o meio</strong> — o servidor precisa aceitar o pedido de trecho do vídeo (o Apache aceita); avise o suporte.</li>
</ul>
