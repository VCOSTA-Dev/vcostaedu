<h2>Para que serve</h2>
<p>Para escolher o papel certo de cada pessoa e responder à família quando ela pergunta por que vê (ou não vê) um filho ou um ano.</p>
<h2>Antes de começar</h2>
<ul>
<li>A pessoa está cadastrada em <strong>Responsáveis</strong> e tem um papel no aluno, no ano.</li>
</ul>
<h2>Passo a passo</h2>
<ol>
<li>Confira o papel da pessoa na tela dos responsáveis do aluno (<strong>Alunos</strong>, a ficha, <strong>Abrir os responsáveis do aluno</strong>), no ano.</li>
<li>O que cada papel vê no portal, naquele aluno e naquele ano:</li>
</ol>
<table>
<thead><tr><th>papel</th><th>o acompanhamento escolar (boletim, notas, frequência, horário, turma, atestado)</th></tr></thead>
<tbody>
<tr><td>Responsável financeiro</td><td>sim</td></tr>
<tr><td>Acadêmico titular</td><td>sim</td></tr>
<tr><td>Acesso acadêmico adicional</td><td>sim, enquanto a escola permitir o acesso adicional (Regras da escola)</td></tr>
<tr><td>Sem papel naquele ano</td><td>não</td></tr>
</tbody>
</table>
<ol>
<li>O papel vale por ano: quem foi o financeiro em 2025 e não tem papel em 2026 vê só 2025.</li>
<li>Tirar o papel, trocar o financeiro ou encerrar o acesso adicional vale na próxima tela que a pessoa abrir; ela não precisa sair do portal.</li>
<li>Bloquear o acesso da pessoa tira tudo, de todos os alunos, até desbloquear.</li>
</ol>
<p>Nenhum papel vê, pelo portal, a senha do aluno, o ambiente de estudo ou os outros responsáveis do aluno.</p>
<h2>O que pode dar errado</h2>
<ul>
<li><strong>A pessoa não vê um filho:</strong> ela não tem papel em vigor naquele aluno, ou só tem o acesso adicional e a escola o desligou.</li>
<li><strong>A pessoa não vê um ano:</strong> não há papel dela naquele aluno, naquele ano. Designe pelo ano certo, ou use <strong>Copiar do ano anterior</strong>.</li>
</ul>
