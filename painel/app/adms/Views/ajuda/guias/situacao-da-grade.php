<h2>Para que serve</h2>
<p>Controlar a vida da grade:</p>
<ul>
<li><strong>Finalizada</strong> é a matriz oficial da turma;</li>
<li><strong>Desativada</strong> não aceita aluno nem oferta nova;</li>
<li><strong>reabrir</strong> (voltar para Aberta) permite mudar a grade de novo.</li>
</ul>
<h2>Antes de começar</h2>
<p>A secretaria montou a grade e a mandou para <strong>Em análise</strong>.</p>
<h2>Passo a passo</h2>
<ol>
<li>Menu <strong>Ensino → Matriz</strong>, abra a grade do curso. Travada, a grade mostra uma faixa com o botão <strong>Ir para a situação da grade</strong>.</li>
<li>Em <strong>Situação da grade</strong>, escolha a nova situação. Escreva a <strong>justificativa</strong>: é <strong>obrigatória para reabrir</strong> uma grade Finalizada ou Desativada e opcional nas outras trocas.</li>
<li>Salve. A troca fica no <strong>Registro de alterações da grade</strong>, com quem mudou e quando.</li>
</ol>
<figure><img src="{{IMG}}administrador_11_grade_situacao.png" alt="Situação da grade"><figcaption>Situação da grade</figcaption></figure>
<h2>O que pode dar errado</h2>
<ul>
<li><strong>&quot;Para reabrir uma grade «Finalizada», escreva a justificativa (ao menos 5 caracteres).&quot;</strong></li>
<li><strong>Só aparecem as situações que o seu perfil pode escolher.</strong> No quadro <strong>Situação da grade</strong>, a secretaria vê só <strong>«Em análise»</strong> (e só com a grade <strong>Aberta</strong>); finalizar, desativar e reabrir não aparecem para ela — são do administrador. Se o quadro nem aparece, não há mudança que o seu perfil possa fazer nessa grade.</li>
<li>Grade <strong>Desativada</strong>: a oferta recusa com <strong>&quot;A grade N está Desativada: não gera oferta.&quot;</strong> e o vínculo com <strong>&quot;… está Desativada e não aceita vínculo novo.&quot;</strong> — reabra, se for o caso.</li>
</ul>
