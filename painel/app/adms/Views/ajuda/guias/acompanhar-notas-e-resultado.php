<h2>Para que serve</h2>
<p>Ver, antes do encerramento, como está cada aluno: média, frequência e o resultado provável.</p>
<h2>Antes de começar</h2>
<p>Há atividades com nota e faltas lançadas.</p>
<h2>Passo a passo</h2>
<ol>
<li>Na disciplina, <strong>Notas e resultado</strong> (nas abas do topo da disciplina, as mesmas em Atividades, Faltas e Encerramento).</li>
<li>Com a disciplina <strong>aberta</strong>, a média é <strong>parcial</strong>: só as atividades que já têm nota entram na conta.</li>
</ol>
<figure><img src="{{IMG}}professor_10_notas_e_resultado_parcial.png" alt="Média parcial da disciplina aberta"><figcaption>Média parcial da disciplina aberta</figcaption></figure>
<ol>
<li>Na linha de cada aluno: a situação da matrícula, uma coluna por atividade, a média (com a etiqueta <strong>parcial</strong>), as faltas, a frequência (em vermelho abaixo do mínimo), o resultado e o botão <strong>Boletim</strong>.</li>
<li><strong>Atualizar lista</strong>: um aluno enturmado depois das atividades ganha as linhas de nota. A enturmação já faz isso sozinha; o botão é para conferir.</li>
<li>Antes de a secretaria encerrar, confira se todas as notas foram lançadas. As regras de cálculo estão no pé da tela.</li>
</ol>
<blockquote>No encerramento, <strong>atividade sem nota conta 0</strong>.</blockquote>
<h2>O que pode dar errado</h2>
<ul>
<li>A média muda depois do encerramento: era parcial; no encerramento as atividades sem nota entram com 0.</li>
<li><strong>Aprovado</strong> exige média <strong>e</strong> frequência mínimas; senão sai <strong>Reprovado por nota</strong>, <strong>por frequência</strong> ou <strong>por nota e frequência</strong>.</li>
</ul>
