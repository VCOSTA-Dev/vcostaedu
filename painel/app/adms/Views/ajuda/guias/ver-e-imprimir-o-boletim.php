<h2>Para que serve</h2>
<p>Mostrar ao aluno ou à coordenação a situação de cada disciplina: média (parcial nas abertas, final nas encerradas), faltas e compensadas, frequência e resultado.</p>
<h2>Antes de começar</h2>
<p>O aluno está vinculado e enturmado.</p>
<h2>Passo a passo</h2>
<ol>
<li>Abra o boletim de um destes lugares:</li>
</ol>
<p>- <strong>Educacional → Alunos</strong>, botão <strong>Boletim</strong> na linha do aluno; - <strong>Notas e resultado</strong> da disciplina, botão <strong>Boletim</strong> na linha do aluno.</p>
<figure><img src="{{IMG}}secretaria_17_boletim.png" alt="Boletim de um aluno reprovado por frequência"><figcaption>Boletim de um aluno reprovado por frequência</figcaption></figure>
<ol>
<li>No topo:</li>
</ol>
<p>- <strong>Curso</strong> e <strong>Ano</strong> filtram o boletim; - <strong>Imprimir</strong> imprime a página sem o menu; - <strong>PDF</strong> gera o mesmo boletim, com o mesmo filtro.</p>
<ol>
<li>Aluno em dois cursos: dois boletins, um abaixo do outro, cada um com a sua faixa.</li>
<li>Na escola, os boletins de uma turma inteira: na tela da turma, ou na do conselho de classe, clique em <strong>Imprimir os boletins da turma</strong>. Sai um PDF só, com o boletim de cada aluno da turma a partir de uma página nova, na ordem dos nomes.</li>
</ol>
<h2>O que pode dar errado</h2>
<ul>
<li>A média tem a etiqueta <strong>&quot;parcial&quot;</strong>: a disciplina está aberta; o valor pode mudar até o encerramento.</li>
<li>Frequência <strong>&quot;—&quot;</strong>: a oferta não tem o total de encontros (<a class="guia-interno" data-guia="completar-a-oferta" href="{{GUIA}}completar-a-oferta">Completar a oferta</a>).</li>
<li>&quot;O aluno não tem matrícula em curso nem disciplina enturmada com este filtro&quot;: mude o filtro para <strong>Todos</strong>.</li>
</ul>
