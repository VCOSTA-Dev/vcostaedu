<h2>Para que serve</h2>
<p>No começo do ano, convidar um por um dá trabalho. Aqui, de uma vez, cada responsável da turma que ainda não tem acesso recebe o convite dele.</p>
<h2>Antes de começar</h2>
<ul>
<li>Os responsáveis estão designados nos alunos da turma, no ano letivo da turma.</li>
<li>Para o envio por e-mail, configure <strong>Configurações → E-mail (SMTP)</strong>. Sem isso, os convites são gerados e todos ficam na lista do envio manual.</li>
</ul>
<h2>Passo a passo</h2>
<ol>
<li>Em <strong>Responsáveis</strong>, clique em <strong>Convidar uma turma</strong>.</li>
<li>Escolha o <strong>ano letivo</strong> e a <strong>turma</strong> e clique em <strong>Ver os responsáveis</strong>. A lista mostra quem ainda não tem acesso e quem está sem e-mail.</li>
<li>Clique em <strong>Gerar os convites e enviar por e-mail</strong>. Uma janela mostra o andamento, um responsável por vez. Não feche a página até terminar.</li>
<li>No fim, clique em <strong>Ver o resultado</strong>. Em <strong>Para o envio manual</strong> ficam os que não receberam por e-mail, cada um com o link e o botão do WhatsApp.</li>
</ol>
<h2>O que pode dar errado</h2>
<ul>
<li><strong>&quot;Nesta turma, todos os responsáveis com papel no ano já têm acesso&quot;:</strong> não há ninguém para convidar.</li>
<li><strong>A página foi fechada no meio:</strong> abra a mesma turma de novo e clique em <strong>Continuar os convites</strong>. Os links do envio manual que já tinham aparecido não voltam: gere de novo pela ficha de cada pessoa.</li>
<li><strong>&quot;Há um lote de convites de outra turma em andamento&quot;:</strong> termine aquele primeiro, abrindo a turma dele.</li>
</ul>
