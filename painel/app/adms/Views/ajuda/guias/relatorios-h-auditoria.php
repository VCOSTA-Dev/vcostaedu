<h2>Para que serve</h2>
<p>Responder <strong>quem mudou o quê, quando e por quê</strong>, e <strong>quem levou dados para fora</strong> do sistema.</p>
<h2>Antes de começar</h2>
<p>Só o administrador vê estes relatórios.</p>
<h2>Passo a passo</h2>
<ol>
<li><strong>Reaberturas de oferta</strong>: cada fechamento substituído, com quem encerrou, quem reabriu, quando e a justificativa.</li>
<li><strong>Trocas e edições de regra de média</strong>: as trocas de regra por oferta (anterior, nova, justificativa) e as criações e edições de regra no catálogo.</li>
<li><strong>Exportações de relatórios</strong>: cada Excel, CSV, PDF ou impressão, com quem, quando, o relatório, os filtros e quantas linhas. O link dos filtros abre o relatório como foi exportado.</li>
<li><strong>Usuários e último acesso</strong>: usuários por perfil, o último login e quem, ativo, não entra há mais de N dias (padrão 90). Use para inativar acessos parados.</li>
</ol>
<h2>O que pode dar errado</h2>
<ul>
<li>O último acesso aparece &quot;nunca&quot;: o usuário nunca entrou, ou entrou antes de o sistema registrar o login.</li>
<li>Uma exportação não aparece: só o que foi exportado pelos botões dos relatórios é registrado (as outras listas do sistema não entram).</li>
</ul>
