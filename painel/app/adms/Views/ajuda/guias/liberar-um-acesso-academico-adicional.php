<h2>Para que serve</h2>
<p>Às vezes, outra pessoa acompanha o aluno: a avó que busca na escola, o padrasto. A escola pode liberar a ela o <strong>acesso acadêmico adicional</strong> naquele ano. Essa pessoa acompanha só o acadêmico; nunca o financeiro, em nenhuma hipótese.</p>
<p>Cada liberação guarda o motivo (obrigatório), a referência do termo ou documento que a apoia, quem liberou e quando. Ela vale só para o ano em que foi dada.</p>
<h2>Antes de começar</h2>
<ul>
<li>Em <strong>Ensino → Regras da escola</strong>, no quadro <strong>Responsáveis</strong>, o acesso adicional precisa estar <strong>permitido</strong> (o padrão). Ali também fica o limite por aluno (0 = sem limite, o padrão).</li>
</ul>
<h2>Passo a passo</h2>
<ol>
<li>Abra os responsáveis do aluno e escolha o ano letivo.</li>
<li>No quadro <strong>Acessos acadêmicos adicionais</strong>, clique em <strong>Liberar um acesso adicional</strong>.</li>
<li>Escolha a pessoa (ou cadastre agora), escreva o <strong>motivo</strong> e a <strong>referência do termo ou documento</strong> (por exemplo, &quot;termo assinado pela mãe em 10/02&quot;).</li>
<li>Clique em <strong>Liberar</strong>.</li>
</ol>
<p>Para encerrar, clique em <strong>Encerrar a liberação</strong> na pessoa, com a data e o motivo.</p>
<h2>O que pode dar errado</h2>
<ul>
<li><strong>&quot;A escola não permite o acesso acadêmico adicional&quot;:</strong> a regra está desligada em Regras da escola. Com ela desligada, as liberações que existirem também deixam de valer.</li>
<li><strong>&quot;O limite de acessos adicionais por aluno já foi atingido&quot;:</strong> encerre uma liberação ou mude o limite em Regras da escola.</li>
<li><strong>&quot;Esta pessoa já é o responsável… neste ano&quot;:</strong> ela já acompanha o aluno; não precisa da liberação.</li>
</ul>
