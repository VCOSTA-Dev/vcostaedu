<h2>Para que serve</h2>
<p>Conferir, antes do ano começar e ao longo dele, quem ainda não tem os responsáveis designados e quem tem o acesso acadêmico adicional.</p>
<h2>Antes de começar</h2>
<ul>
<li>Os alunos estão nas turmas do ano (Turmas).</li>
</ul>
<h2>Passo a passo</h2>
<ol>
<li>Abra <strong>Relatórios</strong>.</li>
<li><strong>Alunos sem responsável financeiro ou sem titular</strong>: escolha o ano letivo (e, se quiser, a turma). A lista mostra, turma a turma, cada aluno a quem falta o financeiro, o titular ou os dois. Os cartões no alto separam os que não têm o financeiro e os que não têm o titular. O nome do aluno abre a tela dos responsáveis dele, no ano.</li>
<li><strong>Acessos acadêmicos adicionais em vigor</strong>: cada liberação que começou e não foi encerrada, com o aluno, a turma, a pessoa, desde quando, o motivo, a referência do termo e quem liberou. O nome da pessoa abre a ficha do responsável.</li>
<li>Os dois relatórios exportam para Excel, CSV e PDF e imprimem, como os outros.</li>
</ol>
<h2>O que pode dar errado</h2>
<ul>
<li><strong>O aluno não aparece em &quot;sem responsável&quot;:</strong> ele tem os dois papéis em vigor no ano, ou não está em nenhuma turma do ano.</li>
<li><strong>Aviso de que a regra está desligada:</strong> em Regras da escola, o acesso adicional está desligado; as liberações continuam listadas, mas não dão acesso ao portal.</li>
</ul>
