<h2>Para que serve</h2>
<p>Entregar de novo um histórico já emitido sem gerar outro documento: mesmo conteúdo, mesmo código.</p>
<h2>Antes de começar</h2>
<p>A emissão está <strong>válida</strong> (não cancelada).</p>
<h2>Passo a passo</h2>
<ol>
<li><strong>Educacional → Históricos emitidos</strong> (ou a aba Históricos da ficha), <strong>Ver</strong> na emissão.</li>
<li><strong>Gerar 2ª via</strong>. Sai o mesmo documento, com a marca <strong>&quot;2ª VIA — reimpressão de …&quot;</strong> no topo de cada página; fica registrado quem gerou e quando.</li>
<li>Baixe o PDF da via na lista <strong>Documentos</strong>.</li>
</ol>
<h2>O que pode dar errado</h2>
<ul>
<li><strong>&quot;Emissão cancelada não tem 2ª via.&quot;</strong></li>
<li><strong>&quot;Os dados gravados desta emissão NÃO conferem com o hash: 2ª via recusada.&quot;</strong> — o registro foi alterado; avise o administrador.</li>
<li>Precisa de um documento com dados novos? Não é 2ª via: emita de novo.</li>
</ul>
