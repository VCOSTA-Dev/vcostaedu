<h2>Para que serve</h2>
<p>Voltar a entrar no portal quando a senha foi esquecida.</p>
<h2>Antes de começar</h2>
<p>Precisa haver um e-mail no seu cadastro. Sem e-mail, peça à secretaria um link novo.</p>
<h2>Passo a passo</h2>
<ol>
<li>Na tela de entrada, clique em <strong>Esqueci a senha</strong> e informe o seu usuário.</li>
<li>Você recebe no e-mail um link para definir a nova senha (como no <a class="guia-interno" data-guia="primeiro-acesso-do-aluno" href="{{GUIA}}primeiro-acesso-do-aluno">primeiro acesso</a>).</li>
</ol>
<figure><img src="{{IMG}}aluno_03_esqueci_a_senha.png" alt="Esqueci a senha"><figcaption>Esqueci a senha</figcaption></figure>
<blockquote>Por segurança, a resposta da tela é sempre a mesma, exista ou não o cadastro.</blockquote>
<h2>O que pode dar errado</h2>
<ul>
<li>O e-mail não chegou: confira a caixa de spam; se não houver e-mail no cadastro, a secretaria envia o link pela sua ficha.</li>
<li><strong>&quot;Este link é inválido, já foi usado ou expirou. …&quot;</strong> — peça outro.</li>
<li><strong>&quot;Muitas tentativas. Aguarde N minuto(s) e tente de novo.&quot;</strong> — depois de alguns pedidos seguidos, a tela pede uma espera (começa em 30 segundos e dobra a cada novo pedido, até 15 minutos). Espere e peça de novo, ou procure a secretaria.</li>
</ul>
