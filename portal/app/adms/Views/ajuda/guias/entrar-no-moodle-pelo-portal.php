<h2>Para que serve</h2>
<p>Entrar no Moodle da instituição direto do portal, sem digitar outra senha, e abrir cada disciplina já no lugar certo.</p>
<h2>Antes de começar</h2>
<p>Os botões aparecem quando a instituição ligou o portal ao Moodle, a sua matrícula está ativa e as suas disciplinas já foram enviadas ao Moodle pela secretaria.</p>
<h2>Passo a passo</h2>
<ol>
<li>Entre no portal e, na <strong>Página Inicial</strong>, procure o cartão <strong>Moodle</strong>.</li>
<li>Clique em <strong>Entrar no Moodle</strong> para abrir a página inicial do Moodle, já com você conectado.</li>
<li>Ou clique em <strong>Abrir no Moodle</strong> ao lado de uma disciplina, para ir direto a ela.</li>
</ol>
<h2>O que pode dar errado</h2>
<ul>
<li><strong>O cartão Moodle não aparece</strong> — a matrícula está trancada ou cancelada, ou as suas disciplinas ainda não foram enviadas ao Moodle. Procure a secretaria.</li>
<li><strong>&quot;O acesso ao Moodle por aqui não está disponível para você agora.&quot;</strong> — o mesmo motivo; procure a secretaria.</li>
<li><strong>&quot;Muitas entradas no Moodle na última hora.&quot;</strong> — espere alguns minutos e tente de novo.</li>
<li><strong>&quot;O Moodle não respondeu agora.&quot;</strong> — tente de novo em alguns minutos.</li>
</ul>
