<h2>Para que serve</h2>
<p>Ver <strong>quanto falta para concluir</strong> o curso, disciplina por disciplina.</p>
<h2>Antes de começar</h2>
<p>Entre no portal. Você vê só as suas matrículas.</p>
<h2>Passo a passo</h2>
<ol>
<li>Abra <strong>Acadêmico → Meu progresso</strong>.</li>
<li>Se você tem mais de um curso, escolha o curso no topo.</li>
<li>Veja a <strong>carga horária cumprida</strong>, as <strong>disciplinas aprovadas</strong> e a <strong>média final</strong> (só das disciplinas encerradas).</li>
<li>Na tabela, cada disciplina da grade: <strong>Aprovado</strong>, <strong>Reprovado</strong>, <strong>Em curso</strong> ou <strong>Não cursada</strong>, com a média e a frequência.</li>
</ol>
<h2>O que pode dar errado</h2>
<ul>
<li>A média de uma disciplina &quot;em curso&quot; mudou: ela é parcial (só das atividades com nota) até o encerramento.</li>
<li>Uma disciplina aparece &quot;Não cursada&quot;, mas você está na turma: fale com a secretaria (pode faltar a enturmação).</li>
</ul>
