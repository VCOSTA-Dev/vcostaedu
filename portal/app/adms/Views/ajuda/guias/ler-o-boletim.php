<h2>Para que serve</h2>
<p>Acompanhar a sua situação em cada disciplina e imprimir o boletim quando precisar.</p>
<h2>Antes de começar</h2>
<p>Você está enturmado nas disciplinas do ano.</p>
<h2>Passo a passo</h2>
<ol>
<li>Menu <strong>Boletim</strong>. No topo, uma faixa com o seu nome, RA, curso e situação; abaixo, a lista das disciplinas do curso.</li>
</ol>
<figure><img src="{{IMG}}aluno_05_boletim.png" alt="Boletim do aluno"><figcaption>Boletim do aluno</figcaption></figure>
<ol>
<li>Como ler:</li>
</ol>
<p>- <strong>Média com a etiqueta &quot;parcial&quot;</strong>: a disciplina está aberta; é a média só das atividades com nota e pode mudar; - <strong>Média sem etiqueta</strong>: a disciplina foi encerrada; é a média final; - <strong>Faltas</strong> e <strong>Comp.</strong> (faltas compensadas): as compensadas não contam contra você; - <strong>Frequência</strong> = 1 − (faltas − compensadas) ÷ total de encontros; - <strong>Resultado</strong>: <strong>Em curso</strong>, <strong>Aprovado</strong> ou <strong>Reprovado</strong> (por nota, por frequência ou pelos dois). - O que está <strong>em vermelho</strong> está abaixo do mínimo.</p>
<ol>
<li>Para ver só um ano ou um curso, use os seletores <strong>Curso</strong> e <strong>Ano</strong> no topo.</li>
<li><strong>Imprimir</strong> tira o menu e imprime só o boletim.</li>
<li><strong>Como foi calculado</strong> (embaixo de cada curso, recolhido): clique para abrir a conta de cada disciplina — as notas de cada componente, os pesos, o arredondamento e a frequência.</li>
</ol>
<blockquote>A conta segue a regra de média da instituição, do curso ou da disciplina. No encerramento, conforme a regra, atividade sem nota conta 0.</blockquote>
<h2>O que pode dar errado</h2>
<ul>
<li>Aparece <strong>&quot;—&quot;</strong> na média: a disciplina está aberta e a instituição mostra a média só no encerramento.</li>
<li><strong>&quot;Reprovado por frequência&quot;</strong> com média boa: a aprovação exige média <strong>e</strong> frequência. Atestados são lançados pela secretaria como faltas compensadas; procure a secretaria.</li>
<li>Nota ou falta errada: fale com o professor ou a secretaria.</li>
</ul>
